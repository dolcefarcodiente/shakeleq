let lang = (localStorage.getItem('lang') || (navigator.language||'en').slice(0,2));
if (!I18N[lang]) lang = 'en';
const t = k => (I18N[lang][k] ?? I18N.en[k] ?? k);

function applyLang(){
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang===lang)));
  document.getElementById('grid').dataset.empty = t('works.empty');
  document.getElementById('lightbox').setAttribute('aria-label', t('lb.label'));
  renderGrid(); renderHero();
}
document.querySelectorAll('[data-lang]').forEach(b => b.addEventListener('click', () => {
  lang = b.dataset.lang; localStorage.setItem('lang', lang); applyLang();
}));

/* ───────── menu ───────── */
const burger = document.querySelector('.burger'), menu = document.getElementById('menu');
burger.addEventListener('click', () => {
  const open = menu.classList.toggle('is-open'); burger.setAttribute('aria-expanded', String(open));
});
menu.querySelectorAll('a').forEach(a => a.addEventListener('click', () => { menu.classList.remove('is-open'); burger.setAttribute('aria-expanded','false'); }));

/* ───────── works ───────── */
const WORKS = window.WORKS || [];
let filter = 'all', visible = [];
const grid = document.getElementById('grid');

function imgHTML(w, cls=''){
  return `<img src="${w.src}" alt="${w.title[lang]}, ${w.year}" loading="lazy" class="${cls}"
    onload="this.classList.add('is-loaded')"
    onerror="this.replaceWith(Object.assign(document.createElement('div'),{className:'ph ${w.ph}'}))">`;
}
function caption(w){
  return `<span class="t">${w.title[lang]}, ${w.year}</span>${w.medium[lang]}, ${w.size}<br><span class="status ${w.status}">${t('status.'+w.status)}</span>`;
}
function renderGrid(){
  visible = WORKS.filter(w => filter==='all' ? true : filter==='available' ? w.status==='available' : w.type===filter);
  grid.classList.toggle('is-empty', visible.length===0);
  grid.innerHTML = visible.map((w,i) => `
    <figure class="work" style="--ratio:${w.ratio}">
      <button type="button" data-i="${i}" aria-label="${w.title[lang]}, ${w.year}"><div class="img">${imgHTML(w)}</div></button>
      <figcaption>${caption(w)}</figcaption>
    </figure>`).join('');
}
grid.addEventListener('click', e => { const b = e.target.closest('button[data-i]'); if (b) openLB(+b.dataset.i); });

document.querySelectorAll('.chip').forEach(c => c.addEventListener('click', () => {
  filter = c.dataset.filter;
  document.querySelectorAll('.chip').forEach(x => { const on = x===c; x.classList.toggle('is-active', on); x.setAttribute('aria-pressed', String(on)); });
  renderGrid();
}));

function renderHero(){
  const w = WORKS.find(x => x.featured) || WORKS[0]; if (!w) return;
  document.getElementById('hero-art').innerHTML = imgHTML(w) + `<figcaption>${w.title[lang]}, ${w.year} · ${w.medium[lang]}</figcaption>`;
}

/* ───────── lightbox ───────── */
const lb = document.getElementById('lightbox'), lbImg = document.getElementById('lb-img'), lbCap = document.getElementById('lb-cap');
let cur = 0, lastFocus = null;
function showLB(){
  const w = visible[cur];
  lbImg.innerHTML = imgHTML(w).replace('loading="lazy"','');
  lbCap.innerHTML = caption(w);
}
function openLB(i){ cur = i; lastFocus = document.activeElement; showLB(); lb.hidden = false; document.body.style.overflow='hidden'; document.getElementById('lb-close').focus(); }
function closeLB(){ lb.hidden = true; document.body.style.overflow=''; if (lastFocus) lastFocus.focus(); }
function step(d){ cur = (cur + d + visible.length) % visible.length; showLB(); }
document.getElementById('lb-close').addEventListener('click', closeLB);
document.getElementById('lb-prev').addEventListener('click', () => step(-1));
document.getElementById('lb-next').addEventListener('click', () => step(1));
lb.addEventListener('click', e => { if (e.target === lb) closeLB(); });
document.addEventListener('keydown', e => {
  if (lb.hidden) return;
  if (e.key === 'Escape') closeLB();
  else if (e.key === 'ArrowRight') step(1);
  else if (e.key === 'ArrowLeft') step(-1);
  else if (e.key === 'Tab') { // trap focus
    const f = [...lb.querySelectorAll('button')]; const first = f[0], last = f[f.length-1];
    if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
    else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
  }
});

document.getElementById('year').textContent = new Date().getFullYear();
applyLang();
